DROP DATABASE IF EXISTS library;
CREATE DATABASE library DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE library;

-- 외래키 순서를 고려해 자식 테이블부터 삭제
DROP TABLE IF EXISTS loan;
DROP TABLE IF EXISTS book;
DROP TABLE IF EXISTS member;

-- ---------------------------------------------------------------------
-- 회원(member) : 도서관 이용자
-- ---------------------------------------------------------------------
CREATE TABLE member (
  member_id   INT AUTO_INCREMENT PRIMARY KEY,
  name        VARCHAR(30)  NOT NULL,
  dept        VARCHAR(40),                      -- 학과
  member_type VARCHAR(10)  NOT NULL DEFAULT '학부생',  -- 학부생 / 대학원생 / 교직원
  email       VARCHAR(60),
  join_date   DATE         NOT NULL             -- 가입일
);

-- ---------------------------------------------------------------------
-- 도서(book) : 소장 도서
-- ---------------------------------------------------------------------
CREATE TABLE book (
  book_id      INT AUTO_INCREMENT PRIMARY KEY,
  title        VARCHAR(100) NOT NULL,
  author       VARCHAR(50),
  publisher    VARCHAR(50),
  pub_year     INT,                             -- 출판연도
  category     VARCHAR(20),                     -- 컴퓨터/문학/역사/과학/사회/예술
  isbn         VARCHAR(20),
  total_copies INT          NOT NULL DEFAULT 1  -- 소장 부수
);

-- ---------------------------------------------------------------------
-- 대출(loan) : 회원이 도서를 빌린 기록
--   return_date 가 NULL 이면 아직 반납하지 않은 상태
-- ---------------------------------------------------------------------
CREATE TABLE loan (
  loan_id     INT AUTO_INCREMENT PRIMARY KEY,
  member_id   INT  NOT NULL,
  book_id     INT  NOT NULL,
  loan_date   DATE NOT NULL,                    -- 대출일
  due_date    DATE NOT NULL,                    -- 반납예정일
  return_date DATE,                             -- 실제 반납일 (NULL = 미반납)
  CONSTRAINT fk_loan_member FOREIGN KEY (member_id) REFERENCES member(member_id),
  CONSTRAINT fk_loan_book   FOREIGN KEY (book_id)   REFERENCES book(book_id)
);

